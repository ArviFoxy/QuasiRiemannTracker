"""Assemble a marked density chain in Lean from generated step certificates.

Input: a steps JSON (the format of `gen_hybrid.py --steps`: a list of
{"B0","L0","c0","B","L","c","A","D"[,"floor"]} as exact rationals, each child equal to the next parent),
the floor `qf` of the certificates, and the Lean module/namespace pattern of the step certificates
(as written by `gen_hybrid.py --marked --steps ... --module-pattern ...`).

Output: one Lean module with
* `boot hβ : GlobalSource 99999/100000 5143/2000 1397/10000` (PR 86's native chain and subface step,
  `QRH.SilDensitySplit.K15.boot_source`), unless the first parent is given otherwise with --boot-term;
* `source_NN hβ : GlobalSource B_NN L_NN c_NN` for every step NN (each from `source_(NN-1)` by
  `Density.density_step_marked`), so every chain face is available (count/physical role split);
* `final_source hβ` = the last one.

usage: python3 gen_chain.py steps.json --floor 3/5 --step-import 'Submissions.arvi_density.Chain.Step_{i:02d}'
         --step-namespace QRH.ArviDensity.Chain --step-module 'Step_{i:02d}'
         --module-namespace QRH.ArviDensity.Chain -o Chain.lean
"""
import argparse, json
from fractions import Fraction as Fr

BOOT = (Fr(99999, 100000), Fr(5143, 2000), Fr(1397, 10000))


def q(x):
    return Fr(str(x)) if not isinstance(x, Fr) else x


def lean(x):
    x = q(x)
    return f"({x.numerator} / {x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"


def face(B, L, c):
    return f"QRH.Record1252270103Source.GlobalSource {lean(B)} {lean(L)} {lean(c)}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('steps')
    ap.add_argument('--floor', required=True)
    ap.add_argument('--step-import', required=True, help="Lean module of step i, e.g. 'Submissions.arvi_density.Chain.Step_{i:02d}'")
    ap.add_argument('--step-namespace', required=True, help='namespace of the certificates (gen_hybrid --namespace)')
    ap.add_argument('--step-module', required=True, help="inner module name of step i (gen_hybrid --module), e.g. 'Step_{i:02d}'")
    ap.add_argument('--module-namespace', required=True, help='namespace of the generated chain module')
    ap.add_argument('--start', type=int, default=1, help='number of the first step')
    ap.add_argument('--title', default='marked density chain')
    ap.add_argument('-o', '--output', required=True)
    a = ap.parse_args()
    steps = json.load(open(a.steps))
    qf = q(a.floor)
    first = (q(steps[0]['B0']), q(steps[0]['L0']), q(steps[0]['c0']))
    if first != BOOT:
        raise SystemExit(f'first parent {first} is not the boot face {BOOT}')
    for k in range(1, len(steps)):
        prev, cur = steps[k - 1], steps[k]
        if (q(prev['B']), q(prev['L']), q(prev['c'])) != (q(cur['B0']), q(cur['L0']), q(cur['c0'])):
            raise SystemExit(f'step {k + a.start}: parent is not the previous child')
    for k, s in enumerate(steps):
        if q(s['B0']) < Fr(22, 23):
            raise SystemExit(f'step {k + a.start}: parent B0 < 22/23 (outside the marked gain range)')
    nums = [k + a.start for k in range(len(steps))]
    L = []
    L.append(f"/- {a.title}: {len(steps)} marked density steps at the floor `qf = {qf}` from PR 86's boot face")
    L.append(f"`G(99999/100000, 5143/2000, 1397/10000)` to `G({steps[-1]['B']}, {steps[-1]['L']}, {steps[-1]['c']})`.")
    L.append("Each step is `Density.density_step_marked` applied to a certificate generated by")
    L.append("`research/density/gen_hybrid.py --marked`; this file is generated by `research/density/gen_chain.py`. -/")
    L.append("import Submissions.density_split_fine_chain.Source.ChainK15")
    L.append("import Submissions.arvi_density.Density.StepMarked")
    for i in nums:
        L.append(f"import {a.step_import.format(i=i)}")
    L.append("")
    L.append("set_option autoImplicit false")
    L.append(f"namespace {a.module_namespace}")
    L.append("noncomputable section")
    L.append("open OAI OAI.SevenEighths")
    L.append("")
    L.append("/-- PR 86's boot face: the native chain from the fourth-power face and Sil's subface step. -/")
    L.append("theorem boot (hβ : (51/100 : ℝ) ≤ HeckeZeroSupremum.beta) :")
    L.append(f"    {face(*BOOT)} := by")
    L.append("  simpa only [QRH.SilDensitySplit.K15.Face.Source, QRH.SilDensitySplit.K15.bootFace] using")
    L.append("    QRH.SilDensitySplit.K15.boot_source hβ")
    prevname = "boot hβ"
    for i, s in zip(nums, steps):
        cert = f"{a.step_namespace}.hybridGatesM_{a.step_module.format(i=i)}"
        L.append("")
        L.append(f"/-- Step {i}: `G({s['B0']}, {s['L0']}, {s['c0']}) → G({s['B']}, {s['L']}, {s['c']})`,"
                 f" selection `A = {s['A']}`, `D = {s['D']}`. -/")
        L.append(f"theorem source_{i:02d} (hβ : (51/100 : ℝ) ≤ HeckeZeroSupremum.beta) :")
        L.append(f"    {face(s['B'], s['L'], s['c'])} :=")
        L.append(f"  Density.density_step_marked {lean(qf)} {lean(s['B0'])} {lean(s['L0'])} {lean(s['c0'])}")
        L.append(f"    {lean(s['B'])} {lean(s['L'])} {lean(s['c'])} {lean(s['A'])} {lean(s['D'])}")
        L.append(f"    (by norm_num) (by norm_num) (by norm_num) {cert}")
        L.append("    ⟨by norm_num, by norm_num, by norm_num, by norm_num, by norm_num, by norm_num⟩ hβ")
        L.append(f"    ({prevname})")
        prevname = f"source_{i:02d} hβ"
    s = steps[-1]
    L.append("")
    L.append("/-- The end of the marked chain. -/")
    L.append("theorem final_source (hβ : (51/100 : ℝ) ≤ HeckeZeroSupremum.beta) :")
    L.append(f"    {face(s['B'], s['L'], s['c'])} := {prevname}")
    L.append("")
    L.append("end")
    L.append(f"end {a.module_namespace}")
    L.append("")
    L.append(f"#print axioms {a.module_namespace}.final_source")
    open(a.output, 'w').write('\n'.join(L) + '\n')
    print(f'wrote {a.output}: {len(steps)} steps, end face G({s["B"]}, {s["L"]}, {s["c"]})')


if __name__ == '__main__':
    main()
