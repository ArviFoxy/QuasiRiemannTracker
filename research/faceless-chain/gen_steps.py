"""Lean file for the concrete steps of the faceless chain: start -> piece0.node 0 and the junctions
piece(j-1).node (1 - Dy) -> piece j.node 0. Each is SourceValid2 by `decide +kernel`, the HIGH part
through Bernstein trees (`HighValid`, then `highPos_of_valid`).

With `QRH_ASSEMBLY` set it also writes `Chain.lean`, the chain itself for any number of pieces: the
final count face C (the last face), the final physical face P (the last grid face with slope above 3,
`family2.face_P`), their exact values, and `chain_sources`, which runs the source step from the start
face through every piece. The start face's module (`QRH_START_MODULE`) must define the start node
`QRH_NATURAL` and `start_good : ParentGood`; `Graph/Start.lean` must prove `start_source`.
With FACES_JSON it writes the faces C and P for the final return (`gen_return_lean.py FACES_JSON …
0 1 …`).
usage: python3 gen_steps.py OUTDIR [FACES_JSON]"""
import sys, os, json
from fractions import Fraction as Fr
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'repeated-marks'))
import lean_certs as LC
import family2 as F2
import polyq as P
from gen_all import SIG, M, PKG, NS, HEAD, TAIL

def node_at(fam, j, y):
    B, L, B0, L0, sv = fam.polys(j)
    q = (1 - fam.den)*P.ev(L0, y)/(6*P.ev(B0, y))
    return dict(B=P.ev(B, y), L=P.ev(L, y), cap=F2.CAPMAX, q=q, allowance=F2.FEES[0], lowFee=F2.FEES[1], highFee=F2.FEES[2])

from chain_params import START   # the chain's first parent (Collet's natural face by default)

def trees_lean(trees, b):
    rows = []
    for i in range(2):
        rows.append("![" + ", ".join(LC.tree_lean(trees[(b, (i, j))]) for j in range(3)) + "]")
    return "fun k => (![" + ", ".join(rows) + "] : Fin 2 → Fin 3 → Split) k.1 k.2"

def frac(x):
    x = Fr(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

def assembly(fam, natname, start_module):
    """`Chain.lean`: the faces C and P and the chain from the start face through every piece."""
    n = len(fam.H)
    (jC, iC), (jP, iP) = F2.face_C(fam), F2.face_P(fam)
    C, Pf = node_at(fam, jC, iC*fam.Dy), node_at(fam, jP, iP*fam.Dy)
    L = [f"/- Generated by research/faceless-chain/gen_steps.py: the source chain as one family of faces.",
         f"The first parent is `{natname}` ({start_module}); its source theorem is `start_source`",
         f"(Graph/Start.lean). Each of the {n} pieces is an induction along its grid `y = i/2^{fam.m}`",
         "(`piece_sources`); the pieces are joined by the junction steps of `Steps.lean`. -/",
         f"import {PKG}.Graph.Chain", f"import {PKG}.Graph.Start", f"import {PKG}.Faceless.Gen.Steps"]
    L += [f"import {PKG}.Faceless.Gen.Piece{j}" for j in range(n)]
    L += ["set_option autoImplicit false", "set_option maxHeartbeats 400000",
          "namespace QRH.RepeatedMarks.Graph", "noncomputable section",
          "open Record1252270103Finite OAI.SevenEighths QRH.Record1252270103Graph QRH.RepeatedMarks.Finite",
          "open QRH.RepeatedMarks.Faceless", "",
          "/-- The count face (`C`, the last face of the family) and the physical face (`P`, the last grid",
          "face with slope above 3). -/",
          f"def faceC : Source := piece{jC}.node (1 - piece{jC}.Dy)" if iC == 2**fam.m - 1 else
          f"def faceC : Source := piece{jC}.node ({iC} * piece{jC}.Dy)",
          f"def faceP : Source := piece{jP}.node ({iP} * piece{jP}.Dy)", ""]
    for f, nd in (("faceC", C), ("faceP", Pf)):
        for k in ("B", "L", "cap"):
            L += [f"lemma {f}_{k} : {f}.{k} = {frac(nd[k])} := by decide +kernel"]
    L += ["",
          "theorem chain_sources (step : NFStep2) (hβ : (51/100:ℝ)≤HeckeZeroSupremum.beta)",
          "    (hk : 6*(2*HeckeZeroSupremum.beta-1)≤QRH.RepeatedMarks.natK) :",
          "    QRH.Record1252270103Graph.P faceC ∧ QRH.Record1252270103Graph.P faceP := by",
          "  have p_start := QRH.RepeatedMarks.start_source hβ hk",
          "  have p0 := step _ _ _ hβ hk step0_valid QRH.RepeatedMarks.start_good (nf_accounting_node _ _)",
          "    p_start p_start"]
    for j in range(n):
        if j > 0:
            L += [f"  have p{j} := step _ _ _ hβ hk junction{j}_valid (parent_good_of_high junction{j}_valid)",
                  f"    (nf_accounting_node _ _) e{j-1} e{j-1}"]
        L += [f"  have e{j} := piece_last step hβ hk piece{j} piece{j}_certs (by norm_num [piece{j}]) p{j}"]
    L += [f"  refine ⟨e{jC}, ?_⟩" if iC == 2**fam.m - 1 else
          f"  refine ⟨by simpa [faceC] using piece_sources step hβ hk piece{jC} piece{jC}_certs "
          f"(by norm_num [piece{jC}]) p{jC} {iC} (by norm_num), ?_⟩",
          f"  have := piece_sources step hβ hk piece{jP} piece{jP}_certs (by norm_num [piece{jP}]) p{jP} {iP}",
          "    (by norm_num)", "  simpa [faceP] using this", "",
          "end", "end QRH.RepeatedMarks.Graph", ""]
    return "\n".join(L), C, Pf

if __name__ == "__main__":
    out = sys.argv[1]
    fam, _ = F2.build2(SIG, m=M)
    Dy = fam.Dy
    natname = os.environ.get('QRH_NATURAL', 'natural')   # Lean name of the start node
    start_module = os.environ.get('QRH_START_MODULE', None if natname == 'natural' else 'Graph.NaturalCap')
    steps = [("step0", "piece0.node 0", natname, node_at(fam, 0, Fr(0)), START)]
    for j in range(1, len(fam.H)):
        par = node_at(fam, j - 1, 1 - Dy)
        steps.append((f"junction{j}", f"piece{j}.node 0", f"piece{j-1}.node (1 - piece{j-1}.Dy)", node_at(fam, j, Fr(0)), par))
    deps = ["Faceless.Gen.Data"] + ([start_module] if start_module else [])
    L = [HEAD(deps), "open Record1252270103Finite QRH.RepeatedMarks.Finite", ""]
    for name, nt, pt, n, par in steps:
        ok, msgs, trees = LC.check_node(n, par, par, Fr(8))
        assert ok, (name, msgs)
        cr = LC.crossing(n, par)
        L += [f"def {name}_treesL : Branch → Split := {trees_lean(trees, cr)}",
              f"def {name}_treesR : Branch → Split := {trees_lean(trees, n['cap'])}",
              f"theorem {name}_validC : SourceValidC ({nt}) ({pt}) (some ({pt})) := by decide +kernel",
              f"theorem {name}_highL : HighCertAt ({nt}) ({pt}) ({pt}) 8 (crossing ({nt}) ({pt})) {name}_treesL := by",
              "  decide +kernel",
              f"theorem {name}_highR : HighCertAt ({nt}) ({pt}) ({pt}) 8 ({nt}).cap {name}_treesR := by",
              "  decide +kernel",
              f"theorem {name}_q : ({nt}).q < 3/4 := by decide +kernel",
              f"theorem {name}_cell : CellRatio ({nt}) ({pt}) := by decide +kernel",
              f"theorem {name}_valid : SourceValid2 ({nt}) ({pt}) (some ({pt})) := by",
              f"  refine ⟨{name}_validC, highPos_of_valid _ _ _ _ {name}_q ?_, {name}_q, {name}_cell⟩",
              "  intro h hh b hb",
              "  simp only [Option.mem_def, Option.some.injEq] at hh",
              "  subst hh",
              "  simp only [List.mem_cons, List.not_mem_nil, or_false] at hb",
              "  rcases hb with rfl | rfl",
              f"  · exact ⟨_, {name}_highL⟩",
              f"  · exact ⟨_, {name}_highR⟩", ""]
        print(name, "ok; crossing", float(cr))
    L += TAIL
    open(os.path.join(out, "Steps.lean"), 'w').write("\n".join(L))
    src, C, Pf = assembly(fam, natname, start_module)
    if os.environ.get('QRH_ASSEMBLY'):
        open(os.path.join(out, "Chain.lean"), 'w').write(src)
        print("Chain.lean: faces C", F2.face_C(fam), "P", F2.face_P(fam))
    if len(sys.argv) > 2:
        json.dump([{k: frac(nd[k]) for k in ("B", "L", "cap")} for nd in (C, Pf)], open(sys.argv[2], 'w'))
