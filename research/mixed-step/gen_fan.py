"""Lean certificates of the fan: Sil's face -> fan face 1 -> ... -> fan face N, each step SourceValid3
(`decide +kernel` for the scalar gates, the sectors and the cell; HIGH Bernstein trees at both width
endpoints, then `sourceValid3_of_certs`). The HIGH parent of every step is its LOW parent.
usage: python3 gen_fan.py FAN_JSON OUT_LEAN [first last]"""
import sys, os, json
from fractions import Fraction as Fr
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mixed_certs as MC
import lean_certs as LC

PKG = 'Submissions.arvi_mixed_step'

def frac(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator}:ℚ)" if x.denominator != 1 else f"({x.numerator}:ℚ)"

def src(f):
    return "⟨" + ",".join(frac(f[k]) for k in ("B", "L", "cap", "q", "allowance", "lowFee", "highFee")) + "⟩"

def trees_lean(trees, b):
    rows = []
    for i in range(2):
        rows.append("![" + ", ".join(LC.tree_lean(trees[(b, (i, j))]) for j in range(3)) + "]")
    return "fun k => (![" + ", ".join(rows) + "] : Fin 2 → Fin 3 → Split) k.1 k.2"

def main():
    fan = [{k: Fr(v) for k, v in f.items()} for f in json.load(open(sys.argv[1]))]
    out = sys.argv[2]
    first = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    last = int(sys.argv[4]) if len(sys.argv) > 4 else len(fan) - 1
    L = ["/- Generated by research/mixed-step/gen_fan.py: the fan from Sil's face down to the stall line.",
         "Every step is a mixed source step (`SourceValid3`) whose LOW and HIGH parent is the previous face. -/",
         f"import {PKG}.Finite.HighGate3",
         "import Submissions.arvi_repeated_marks_on_sil_face_20261025.Graph.StartFace",
         "set_option autoImplicit false", "set_option maxRecDepth 100000",
         "namespace QRH.MixedStep.Fan", "open Record1252270103Finite QRH.RepeatedMarks QRH.RepeatedMarks.Finite QRH.MixedStep.Finite", ""]
    for k in range(first, last + 1):
        n, par = fan[k], fan[k - 1]
        pname = "QRH.RepeatedMarks.start" if k == 1 else f"fan{k-1}"
        L += [f"def fan{k} : Source := {src(n)}"]
        ok, msgs, trees = MC.check_node(n, par, par, Fr(8))
        assert ok and MC.cell_ok(n, par), (k, msgs)
        cr = LC.crossing(n, par)
        L += [f"def fan{k}_treesL : Branch → Split := {trees_lean(trees, cr)}",
              f"def fan{k}_treesR : Branch → Split := {trees_lean(trees, n['cap'])}",
              f"theorem fan{k}_validC : SourceValidC3 fan{k} {pname} {pname} := by decide +kernel",
              f"theorem fan{k}_highL : HighCertAt3 fan{k} {pname} {pname} 8 (crossing fan{k} {pname}) fan{k}_treesL := by",
              "  decide +kernel",
              f"theorem fan{k}_highR : HighCertAt3 fan{k} {pname} {pname} 8 fan{k}.cap fan{k}_treesR := by",
              "  decide +kernel",
              f"theorem fan{k}_cell : CellRatio3 fan{k} {pname} := by decide +kernel",
              f"theorem fan{k}_valid : SourceValid3 fan{k} {pname} {pname} := by",
              f"  refine sourceValid3_of_certs _ _ _ fan{k}_validC ?_ fan{k}_cell",
              "  intro b hb",
              "  simp only [List.mem_cons, List.not_mem_nil, or_false] at hb",
              "  rcases hb with rfl | rfl",
              f"  · exact ⟨_, fan{k}_highL⟩",
              f"  · exact ⟨_, fan{k}_highR⟩", ""]
    L += ["end QRH.MixedStep.Fan", ""]
    open(out, 'w').write("\n".join(L))

if __name__ == '__main__':
    main()
