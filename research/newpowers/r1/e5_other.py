def f4_decompose(r):
    """r in (O/4)^*, r = zeta*(1+2x): return (zeta_index in {0,1,2}, x in O/2 as tuple)"""
    for zi, z in enumerate([(1, 0), (0, 1), (-1, -1)]):
        # z^{-1} r - 1 must be 0 mod 2:  z^{-1} = conj(z) for roots of unity
        t = mul(conj(z), r)
        d = (t[0] - 1, t[1])
        if d[0] % 2 == 0 and d[1] % 2 == 0:
            return zi, ((d[0] // 2) % 2, (d[1] // 2) % 2)
    raise ValueError(r)


def f4_mul(x, y):
    # O/2 : (a + b w)(c + d w) = (ac - bd) + (ad + bc - bd) w   mod 2
    return ((x[0] * y[0] - x[1] * y[1]) % 2, (x[0] * y[1] + x[1] * y[0] - x[1] * y[1]) % 2)


def f4_tr(z):
    # Tr_{F4/F2}(z) = z + z^2 ; for z=a+bw: z^2 = a + b w^2 = (a-b) - b w ; sum = (2a - b) - b w -> mod 2: (b, b)?? use explicit
    z2 = f4_mul(z, z)
    s = ((z[0] + z2[0]) % 2, (z[1] + z2[1]) % 2)
    assert s in ((0, 0), (1, 0))
    return s[0]


