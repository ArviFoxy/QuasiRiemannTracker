/* Fast cubic Gauss sums at split primes of Z[omega] (helper for fastgauss.py).

   For every entry i the routine returns the UNNORMALISED sum

       G_i = sum_{x mod p} chi(x) * exp(-2 pi i * x * b / p),     p = p_arr[i],

   where chi(x) = omega^{t(x)} (omega = e^{2 pi i/3}), x^{(p-1)/3} = r^{t(x)} (mod p), chi(0) = 0,
   r = r_arr[i] the image of omega in Z[omega]/pi, and b = b_arr[i] the omega-coordinate of the primary
   generator pi = a + b*omega.  This is exactly zw.gauss_direct for a prime n (same chi, same additive character),
   only O(p) with a small constant.

   Method.  g = primitive root mod p (supplied).  rho = g^((p-1)/3).  x = g^i has t(x) = i*s mod 3 with s = 1 if
   r == rho and s = 2 if r == rho^2.  chi(-x) = chi(x) (the order of chi is 3 and p = 1 mod 6), so
   G = 2 * sum_{x=1}^{(p-1)/2} chi(x) cos(2 pi x b / p).  The class table is filled by walking g^i for
   i < (p-1)/2 (Barrett reduction), and cos(x*phi) is generated by the Chebyshev recurrence.
*/
#include <stdint.h>
#include <stdlib.h>
#include <math.h>
#include <omp.h>

typedef unsigned __int128 u128;

static inline uint64_t mulmod(uint64_t a, uint64_t b, uint64_t p, uint64_t m) {
    uint64_t prod = a * b;                       /* a, b < p < 2^32 */
    uint64_t q = (uint64_t)(((u128)prod * m) >> 64);
    uint64_t r = prod - q * p;
    if (r >= p) r -= p;
    return r;
}

static uint64_t powmod_(uint64_t a, uint64_t e, uint64_t p, uint64_t m) {
    uint64_t res = 1;
    a %= p;
    while (e) {
        if (e & 1) res = mulmod(res, a, p, m);
        a = mulmod(a, a, p, m);
        e >>= 1;
    }
    return res;
}

void gauss_primes(int64_t n, const int64_t *p_arr, const int64_t *g_arr, const int64_t *r_arr,
                  const int64_t *b_arr, double *out_re, double *out_im, int nthreads) {
    const double TWO_PI = 6.283185307179586476925286766559;
    #pragma omp parallel num_threads(nthreads)
    {
        uint8_t *tab = NULL;
        int64_t cap = 0;
        #pragma omp for schedule(dynamic, 8)
        for (int64_t i = 0; i < n; i++) {
            uint64_t p = (uint64_t)p_arr[i], g = (uint64_t)g_arr[i], r = (uint64_t)r_arr[i];
            int64_t bb = b_arr[i] % (int64_t)p;
            if (bb < 0) bb += (int64_t)p;
            uint64_t m = (uint64_t)((((u128)1) << 64) / p);
            if (cap < (int64_t)p + 1) {
                free(tab);
                cap = (int64_t)p + 1;
                tab = (uint8_t *)malloc((size_t)cap);
            }
            uint64_t rho = powmod_(g, (p - 1) / 3, p, m);
            int s = (rho == r % p) ? 1 : 2;
            uint64_t h = (p - 1) / 2;
            uint64_t x = 1;
            int cls = 0;                                   /* t = i*s mod 3, updated incrementally */
            for (uint64_t j = 0; j < h; j++) {
                tab[x] = (uint8_t)cls;
                tab[p - x] = (uint8_t)cls;
                x = mulmod(x, g, p, m);
                cls += s;
                if (cls >= 3) cls -= 3;
            }
            double phi = TWO_PI * (double)bb / (double)p;
            double c1 = cos(phi), two = 2.0 * c1;
            double cm = 1.0, cc = c1, c[3] = {0.0, 0.0, 0.0};
            for (uint64_t xx = 1; xx <= h; xx++) {
                c[tab[xx]] += cc;
                double cn = two * cc - cm;
                cm = cc;
                cc = cn;
            }
            /* G = 2 (c0 + c1 w + c2 w^2),  w = -1/2 + i sqrt(3)/2 */
            double re = 2.0 * (c[0] - 0.5 * (c[1] + c[2]));
            double im = 2.0 * (0.8660254037844386467637231707529 * (c[1] - c[2]));
            out_re[i] = re;
            out_im[i] = im;
        }
        free(tab);
    }
}
